"""Write farfield_small.fdtd.json: plane wave on a small PEC sphere (ka = 0.05 to 0.26).

A sphere of radius 5 cm on a 5 mm grid, probed from 0.05 to 0.25 GHz, stays in the
low-frequency regime. Its bistatic RCS is close to uniform in theta, with few deep
nulls, unlike the 0.2 m sphere in farfield.fdtd.json (ka up to 3.4).
Run from any directory: python3 make_farfield_small.py
"""
import json
import os

DX = 0.005           # cell size [m]
N = 72               # cells per side
DT = 7.7e-12         # 0.8 x the 3D Courant limit DX / (c * sqrt(3)) = 9.6e-12; the solver applies this factor itself
STEPS = 3900         # same ~30 ns window as the other cases
PML_LAYERS = 12      # absorbs outgoing waves; clear of the far-field box
RADIUS = 10          # sphere radius in cells (5 cm)
CENTER = 36          # sphere centre index on each axis
TF_BOX = [[18, 18, 18], [54, 54, 54]]    # total field region, encloses the sphere
FF_BOX = [[14, 14, 14], [58, 58, 58]]    # far field surface, in the scattered field zone, clear of the PML


def sphere_intervals():
    """Staircase voxels: x-runs of cells whose index lies inside the sphere."""
    runs = []
    for k in range(1, N + 1):
        for j in range(1, N + 1):
            i_in = [i for i in range(1, N + 1)
                    if (i - CENTER) ** 2 + (j - CENTER) ** 2 + (k - CENTER) ** 2 <= RADIUS ** 2]
            if not i_in:
                continue
            start = prev = i_in[0]
            for i in i_in[1:] + [None]:
                if i is not None and i == prev + 1:
                    prev = i
                    continue
                runs.append([[start, j, k], [prev, j, k]])
                if i is not None:
                    start = prev = i
    return runs


case = {
    "format": "FDTD Input file",
    "__comments": "PEC sphere (radius 5 cm) under a plane wave, ka = 0.05 to 0.26. Smooth bistatic RCS. "
                  "Generated by make_farfield_small.py.",
    "general": {"timeStep": DT, "numberOfSteps": STEPS},
    "boundary": {"all": {"type": "pml", "layers": PML_LAYERS, "order": 2.0, "reflection": 0.001}},
    "materials": [{"id": 1, "type": "pec"}],
    "mesh": {
        "grid": {
            "numberOfCells": [N, N, N],
            "steps": {"x": [DX], "y": [DX], "z": [DX]},
        },
        "elements": [
            {"id": 1, "type": "cell", "intervals": [TF_BOX]},
            {"id": 2, "type": "cell", "intervals": [FF_BOX]},
            {"id": 3, "type": "cell", "intervals": sphere_intervals()},
        ],
    },
    "materialAssociations": [{"materialId": 1, "elementIds": [3]}],
    "sources": [
        {
            "type": "planewave",
            "magnitudeFile": "gauss_wide.exc",
            "elementIds": [1],
            "direction": {"theta": 0.0, "phi": 0.0},
            "polarization": {"theta": 1.5708, "phi": 0.0},
        }
    ],
    "probes": [
        {
            "name": "far_field_small",
            "type": "farField",
            "elementIds": [2],
            "theta": {"initial": 0, "final": 180, "step": 1},
            "phi": {"initial": 0, "final": 90, "step": 90},
            "domain": {
                "type": "frequency",
                "initialFrequency": 5e7,
                "finalFrequency": 2.5e8,
                "numberOfFrequencies": 9,
                "frequencySpacing": "linear",
            },
        }
    ],
}

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "farfield_small.fdtd.json"), "w") as f:
    json.dump(case, f, indent=4)
    f.write("\n")
